// Generated part of every page's <head>: language memory script (web/js/taal.js),
// Open Graph / Twitter metadata and JSON-LD. Everything is derived from what the page
// already states about itself (lang, <title>, meta description, canonical, hreflang,
// breadcrumbs), so the block is always in the page's own language.
// The block sits between the two markers below, right after the hreflang links.
import { SITE, HREFLANG, urlOf } from './pages.mjs';

export const START = '<!-- bk-head:start (generated by npm run build:head; do not edit by hand) -->';
export const END = '<!-- bk-head:end -->';

const OG_LOCALE = { nl: 'nl_BE', fr: 'fr_BE' };
const OG_ALT = {
  nl: 'Belastingkaart: Belgische fiscaliteit, helder uitgelegd. Bruto-netto voor werknemers, op basis van officiële bronnen.',
  fr: 'Belastingkaart : la fiscalité belge, expliquée clairement. Brut-net pour salariés, sur la base de sources officielles.'
};
const SITE_DESCRIPTION = {
  nl: 'Bruto-netto simulator en onafhankelijke uitleg over de Belgische loonfiscaliteit voor werknemers, op basis van officiële bronnen.',
  fr: 'Simulateur brut-net et explications indépendantes sur la fiscalité belge des salaires, basés sur des sources officielles.'
};
// schema.org type per page; anything not listed is a WebPage.
const PAGE_TYPE = {
  'nl/contact/': 'ContactPage', 'fr/contact/': 'ContactPage',
  'nl/over-belastingkaart/': 'AboutPage', 'fr/a-propos/': 'AboutPage'
};
export const BRAND_SUFFIX = ' | Belastingkaart';

export function decode(s) {
  return String(s)
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
    .replace(/&nbsp;/g, '\u00a0').replace(/&quot;/g, '"').replace(/&#39;|&apos;/g, "'")
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
}
export const escapeAttr = s => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const stripTags = s => decode(String(s).replace(/<[^>]+>/g, '')).replace(/\s+/g, ' ').trim();
const jsonLd = obj => `<script type="application/ld+json">${JSON.stringify(obj).replace(/</g, '\\u003c')}</script>`;

export function readMeta(html) {
  return {
    lang: html.match(/<html lang="([a-z]{2})/)?.[1],
    title: stripTags(html.match(/<title>([\s\S]*?)<\/title>/)?.[1] ?? ''),
    description: decode(html.match(/<meta name="description" content="([^"]*)"/)?.[1] ?? ''),
    crumbs: html.match(/<p class="breadcrumbs">([\s\S]*?)<\/p>/)?.[1] ?? null
  };
}

// "<a href="../../nl/">Startpagina</a> › Hoe we rekenen" -> [{name, item}, ...]
export function breadcrumbItems(crumbs, route) {
  if (!crumbs) return [];
  const pageUrl = urlOf(route);
  const parts = crumbs.split('›');
  return parts.map((part, i) => {
    const href = part.match(/href="([^"]+)"/)?.[1];
    const item = i === parts.length - 1 ? pageUrl : href ? new URL(href, pageUrl).href : null;
    return { name: stripTags(part), item };
  }).filter(c => c.name && c.item);
}

export function headBlock(html, route) {
  const meta = readMeta(html);
  const lang = route.slice(0, 2);
  if (meta.lang !== lang) throw new Error(`${route}: <html lang> must start with "${lang}"`);
  if (!meta.title || !meta.description) throw new Error(`${route}: <title> and meta description are required`);
  const other = lang === 'nl' ? 'fr' : 'nl';
  const url = urlOf(route);
  const image = `${SITE}/og-${lang}.png`;
  const prefix = '../'.repeat(route.split('/').length - 1);
  const name = meta.title.endsWith(BRAND_SUFFIX) ? meta.title.slice(0, -BRAND_SUFFIX.length) : meta.title;
  const crumbs = breadcrumbItems(meta.crumbs, route);
  const graph = [
    { '@type': 'Organization', '@id': `${SITE}/#organization`, name: 'Belastingkaart', url: `${SITE}/`, logo: `${SITE}/icons/icon-512.png` },
    { '@type': 'WebSite', '@id': `${SITE}/#website`, name: 'Belastingkaart', url: `${SITE}/`, description: SITE_DESCRIPTION[lang],
      inLanguage: [HREFLANG.nl, HREFLANG.fr], publisher: { '@id': `${SITE}/#organization` } },
    { '@type': PAGE_TYPE[route] || 'WebPage', '@id': `${url}#webpage`, url, name, description: meta.description,
      inLanguage: HREFLANG[lang], isPartOf: { '@id': `${SITE}/#website` }, publisher: { '@id': `${SITE}/#organization` },
      primaryImageOfPage: { '@type': 'ImageObject', url: image, width: 1200, height: 630 },
      ...(crumbs.length > 1 ? { breadcrumb: { '@id': `${url}#breadcrumb` } } : {}) }
  ];
  if (crumbs.length > 1) graph.push({ '@type': 'BreadcrumbList', '@id': `${url}#breadcrumb`,
    itemListElement: crumbs.map((c, i) => ({ '@type': 'ListItem', position: i + 1, name: c.name, item: c.item })) });
  const m = (p, c) => `<meta property="${p}" content="${escapeAttr(c)}">`;
  const n = (p, c) => `<meta name="${p}" content="${escapeAttr(c)}">`;
  return [
    START,
    `<script src="${prefix}js/taal.js"></script>`,
    m('og:type', 'website'), m('og:site_name', 'Belastingkaart'), m('og:title', meta.title),
    m('og:description', meta.description), m('og:url', url), m('og:locale', OG_LOCALE[lang]),
    m('og:locale:alternate', OG_LOCALE[other]), m('og:image', image), m('og:image:type', 'image/png'),
    m('og:image:width', '1200'), m('og:image:height', '630'), m('og:image:alt', OG_ALT[lang]),
    n('twitter:card', 'summary_large_image'), n('twitter:title', meta.title),
    n('twitter:description', meta.description), n('twitter:image', image), n('twitter:image:alt', OG_ALT[lang]),
    jsonLd({ '@context': 'https://schema.org', '@graph': graph }),
    END
  ].join('\n');
}

// Returns the page with its generated block inserted or refreshed.
export function applyHead(html, route) {
  const block = headBlock(html, route);
  const s = html.indexOf(START), e = html.indexOf(END);
  if (s >= 0 && e > s) return html.slice(0, s) + block + html.slice(e + END.length);
  const alts = [...html.matchAll(/<link rel="alternate" hreflang="[^"]+" href="[^"]+">\n?/g)];
  if (!alts.length) throw new Error(`${route}: no hreflang alternates to anchor the head block`);
  const last = alts[alts.length - 1];
  const at = last.index + last[0].length;
  return html.slice(0, at) + (last[0].endsWith('\n') ? '' : '\n') + block + '\n' + html.slice(at);
}
